/// Spacing constants used throughout the SyncroFit app.
///
/// All values are in logical pixels (dp). Use these instead of
/// hard-coded numeric values for consistent spacing across screens.
abstract final class AppSpacing {
  /// Extra small spacing: 4dp
  static const double xs = 4;

  /// Small spacing: 8dp
  static const double sm = 8;

  /// Medium spacing: 16dp
  static const double md = 16;

  /// Large spacing: 24dp
  static const double lg = 24;

  /// Extra large spacing: 32dp
  static const double xl = 32;

  /// Double extra large spacing: 48dp
  static const double xxl = 48;
}
